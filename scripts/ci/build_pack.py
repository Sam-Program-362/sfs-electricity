"""Build real platform bundles using a licensed, preconfigured Unity installation.

Runner environment: SFS_UNITY_EDITOR (Unity executable), SFS_TOOLKIT_PROJECT
(inner official toolkit project, with licensed Odin installed). See docs/PACK_BUILD.md.
"""

import base64
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

from validate_pack import PLATFORMS, validate_bundle, validate_pack


ROOT = Path(__file__).resolve().parents[2]
TOOLKIT_REVISION = "855f3eeb094f79c9aa9d27a3d689f51f350b4e06"
UNITY_VERSION = "6000.1.17f1"
BUNDLE_NAME = "n2o4s_electricity"
BUILD_TARGETS = dict(zip(PLATFORMS, ("Win64", "OSXUniversal", "Android", "iOS")))
MARKER = ".sfs-ci-generated"


def git(*args, cwd=ROOT):
    return subprocess.check_output(["git", *args], cwd=cwd, text=True).strip()


def validate_template(template):
    version_path = template / "ProjectSettings/ProjectVersion.txt"
    if not version_path.is_file() or not re.search(
        rf"^m_EditorVersion: {re.escape(UNITY_VERSION)}$",
        version_path.read_text(encoding="utf-8-sig"), re.M,
    ):
        raise ValueError(f"Template must be the inner toolkit project for Unity {UNITY_VERSION}")
    if git("rev-parse", "HEAD", cwd=template) != TOOLKIT_REVISION:
        raise ValueError(f"Toolkit must be pinned to {TOOLKIT_REVISION}")
    if subprocess.run(["git", "diff", "--quiet", "HEAD", "--"], cwd=template).returncode != 0:
        raise ValueError("Toolkit has modified tracked files; restore the pinned template before building")
    for folder in ("Assets", "Packages", "ProjectSettings"):
        if not (template / folder).is_dir():
            raise ValueError(f"Missing template folder: {folder}")
    for dll in ("Sirenix.OdinInspector.Attributes.dll", "Sirenix.OdinInspector.Editor.dll"):
        if not any((template / "Assets").rglob(dll)):
            raise ValueError(f"Install licensed Odin Inspector in the toolkit template: missing {dll}")
    if not (template / "Assets/Editor/Builder.cs").is_file():
        raise ValueError("Official toolkit exporter is missing")


def reset_generated_directory(path):
    """Only replace a directory this tool previously marked as disposable."""
    if path.is_symlink():
        raise ValueError(f"Refusing to replace symlink: {path}")
    if path.exists():
        if not path.is_dir() or not (path / MARKER).is_file():
            raise ValueError(f"Refusing to delete unmanaged directory: {path}")
        shutil.rmtree(path)
    path.mkdir(parents=True)
    (path / MARKER).write_text("Generated by SFS pack CI; safe to rebuild.\n", encoding="utf-8")


def prepare_project(template, workspace, repo=None):
    repo = ROOT if repo is None else repo
    if template == workspace or template.is_relative_to(workspace) or workspace.is_relative_to(template):
        raise ValueError("Toolkit template and generated workspace must be separate directories")
    reset_generated_directory(workspace)
    for folder in ("Assets", "Packages", "ProjectSettings"):
        source = template / folder
        if source.is_symlink() or any(p.is_symlink() for p in source.rglob("*")):
            raise ValueError("Template project must not contain symlinks")
        shutil.copytree(source, workspace / folder)
    destination = workspace / "Assets/Resources/Electricity"
    if destination.exists() or destination.with_suffix(".meta").exists():
        raise ValueError("Use a clean stock toolkit template, without an existing Electricity import")
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(repo / "Electricity", destination)
    shutil.copy2(repo / "Electricity.meta", destination.with_suffix(".meta"))
    editor = workspace / "Assets/Editor/SfsElectricityCI"
    editor.mkdir(parents=True, exist_ok=False)
    shutil.copy2(repo / "build-tools/Editor/SfsPackBuild.cs", editor / "SfsPackBuild.cs")


def source_digest(repo=None):
    repo = ROOT if repo is None else repo
    digest = hashlib.sha256()
    paths = [repo / "Electricity.meta"] + sorted((repo / "Electricity").rglob("*"))
    for path in paths:
        if path.is_file():
            digest.update(path.relative_to(repo).as_posix().encode("utf-8") + b"\0")
            digest.update(hashlib.sha256(path.read_bytes()).digest())
    return digest.hexdigest()


def write_pack(bundles, output):
    """Wrap only actual validated bundles in the official container schema."""
    if set(bundles) != set(PLATFORMS):
        raise ValueError("All four platform bundles are required")
    pack = {}
    for platform in PLATFORMS:
        payload = Path(bundles[platform]).read_bytes()
        validate_bundle(payload)
        pack[platform] = base64.b64encode(payload).decode("ascii")
    pack["CodeAssembly"] = None
    # Atomic publication: no partially written .pack is uploaded after a failure.
    temporary = output.with_suffix(".pack.tmp")
    temporary.write_text(json.dumps(pack, separators=(",", ":")), encoding="utf-8")
    temporary.replace(output)
    return validate_pack(output)


def main():
    unity_env = os.environ.get("SFS_UNITY_EDITOR", "")
    template_env = os.environ.get("SFS_TOOLKIT_PROJECT", "")
    if not unity_env or not template_env:
        raise ValueError("Set SFS_UNITY_EDITOR and SFS_TOOLKIT_PROJECT on the licensed runner; see docs/PACK_BUILD.md")
    unity = Path(unity_env).resolve()
    template = Path(template_env).resolve()
    if not unity.is_file():
        raise ValueError(f"Unity executable not found: {unity}")
    validate_template(template)
    commit = git("rev-parse", "HEAD")
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError("Cannot determine source commit")
    dirty = bool(git("status", "--porcelain"))
    workspace = ROOT / ".build/pack-ci"
    artifacts = ROOT / "artifacts/pack"
    logs = ROOT / "artifacts/logs"
    # Clear stale artifacts even if the new Unity build later fails.
    reset_generated_directory(artifacts)
    reset_generated_directory(logs)
    prepare_project(template, workspace)
    bundles = {}
    for platform, target in BUILD_TARGETS.items():
        output = workspace / "SfsBundleOutput" / platform
        log = logs / f"{platform}.log"
        command = [
            str(unity), "-batchmode", "-nographics", "-quit",
            "-projectPath", str(workspace), "-buildTarget", target,
            "-executeMethod", "SfsElectricity.CI.PackBuilder.BuildPlatform",
            "-sfsPlatform", platform, "-sfsBundleOutput", str(output),
            "-logFile", str(log),
        ]
        print(f"Building {platform} using Unity {UNITY_VERSION}; log: {log}", flush=True)
        process = subprocess.run(command, timeout=2100)
        log_text = log.read_text(encoding="utf-8", errors="replace") if log.exists() else ""
        if process.returncode != 0 or f"SFS_PACK_PLATFORM_OK {platform}" not in log_text:
            raise RuntimeError(f"Unity failed for {platform} (exit {process.returncode}); inspect {log}")
        bundles[platform] = output / BUNDLE_NAME
        validate_bundle(bundles[platform].read_bytes())
    pack = artifacts / f"Electricity_{commit[:12]}.pack"
    platforms = write_pack(bundles, pack)
    checksum = hashlib.sha256(pack.read_bytes()).hexdigest()
    pack.with_suffix(".pack.sha256").write_text(f"{checksum}  {pack.name}\n", encoding="utf-8")
    version = re.search(r"^  Version: (.+)$", (ROOT / "Electricity/Scriptables/PackData.asset").read_text(), re.M)
    metadata = {
        "schema_version": 1,
        "built_at_utc": datetime.now(timezone.utc).isoformat(),
        "source_commit": commit,
        "source_checkout_dirty": dirty,
        "source_assets_sha256": source_digest(),
        "toolkit_commit": TOOLKIT_REVISION,
        "unity_version": UNITY_VERSION,
        "pack_data_version": version[1] if version else None,
        "pack_file": pack.name,
        "pack_sha256": checksum,
        "platforms": platforms,
        "runtime_tested": False,
    }
    (artifacts / "build-info.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"Validated pack created: {pack}", flush=True)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        print(f"Pack build failed: {exc}", file=sys.stderr)
        sys.exit(1)
